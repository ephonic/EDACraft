#!/usr/bin/env python3
"""Exhaust all pairs of two-bit four-state case operands with a character oracle."""
import argparse
import itertools
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    words = [''.join(bits) for bits in itertools.product('01xz', repeat=2)]
    source = ['// Generated by scripts/generate_case_matrix.py.', 'module top;',
              '  reg [7:0] i,j;', '  reg [1:0] s,label;', '  reg [2:0] hit;',
              '  initial begin', "    for(i=0;i<16;i=i+8'd1) begin", '      case(i)']
    source += [f"        8'd{i}: s=2'b{word};" for i, word in enumerate(words)]
    source += ['      endcase', "      for(j=0;j<16;j=j+8'd1) begin", '        case(j)']
    source += [f"          8'd{i}: label=2'b{word};" for i, word in enumerate(words)]
    source += ['        endcase']
    for index, keyword in [(2, 'case'), (1, 'casez'), (0, 'casex')]:
        source += [f'        {keyword}(s)', f"          label: hit[{index}]=1'b1;",
                   f"          default: hit[{index}]=1'b0;", '        endcase']
    source += ['        $display("TRACE s=%b label=%b matches=%b",s,label,hit);',
               '      end', '    end', '    $finish;', '  end', 'endmodule', '']
    expected = []
    for selector in words:
        for label in words:
            matches = []
            for wildcard in ('', 'z', 'xz'):
                match = all(a == b or a in wildcard or b in wildcard for a, b in zip(selector, label))
                matches.append(str(int(match)))
            expected.append(f'TRACE s={selector} label={label} matches={"".join(matches)}')
    return '\n'.join(source), json.dumps(expected, indent=2)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, expected = generate()
    for name, content in [('control_case_matrix.v', source), ('control_case_matrix.expected.json', expected)]:
        path = ROOT/'tests/cases'/name
        if args.check:
            if path.read_text() != content:
                raise RuntimeError(f'Generated fixture is stale: {path}')
        else:
            path.write_text(content)
    print('PASS exhaustive case corpus' if args.check else 'Generated exhaustive case corpus')


if __name__ == '__main__':
    main()
