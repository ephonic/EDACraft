#!/usr/bin/env python3
"""Compile a serial dsim C++ model in bounded translation units.

This is a generated-code build experiment, not an RTL rewrite. The original
source is retained and hashed. Waveform, DPI, gate and parallel models are
rejected because their registration closures need additional environments.
"""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, as_completed
import argparse, hashlib, json, os, re, signal, subprocess, time


def registration_end(source, start):
    """Find the call's closing parenthesis, ignoring strings and comments."""
    pos = source.index('(', start)
    depth = 0
    while pos < len(source):
        c = source[pos]
        if c in '\"\'':
            quote = c
            pos += 1
            while pos < len(source):
                if source[pos] == '\\':
                    pos += 2
                elif source[pos] == quote:
                    pos += 1
                    break
                else:
                    pos += 1
            continue
        if source.startswith('//', pos):
            pos = source.find('\n', pos)
            if pos < 0:
                break
            continue
        if source.startswith('/*', pos):
            end = source.find('*/', pos + 2)
            if end < 0:
                raise ValueError('unterminated generated comment')
            pos = end + 2
            continue
        if c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                if source[pos + 1:pos + 2] != ';':
                    raise ValueError('unexpected generated registration suffix')
                return pos + 2
        pos += 1
    raise ValueError('unterminated generated process registration')


def split(source, batch):
    if '// Generated by dsim ' not in source:
        raise ValueError('requires a dsim generated model')
    for feature in ['WAVE', 'DPI', 'PARALLEL']:
        if '#define DSIM_' + feature + '_ENABLED 1' in source:
            raise ValueError('split experiment does not support ' + feature)
    if '#define DSIM_COMPACT_GATES 1' in source:
        raise ValueError('split experiment requires an RTL model')
    boundary = source.index('int main(int argc,char** argv)')
    common, main = source[:boundary], source[boundary:]
    starts = [m.start() for m in re.finditer(r'^s\.process\(', main, re.M)]
    if not starts:
        raise ValueError('no generated process registrations')
    ends = [registration_end(main, start) for start in starts]
    for i in range(len(starts) - 1):
        gap = main[ends[i]:starts[i + 1]]
        # Only the emitter's optimization pragmas may separate registrations.
        if any(line.strip() and not line.lstrip().startswith('#') for line in gap.splitlines()):
            raise ValueError('non-contiguous generated process registrations')
    channels = sorted({int(m.group(1)) for m in re.finditer(r'^auto continuous_channel(\d+)=s\.continuous_driver\(', main, re.M)})
    if channels != list(range(len(channels))):
        raise ValueError('unexpected continuous channel numbering')
    aliases = ''.join('const auto& continuous_channel%d=channels.at(%d);\n' % (i, i) for i in channels)
    parts = []
    declarations = ''
    calls = 'const std::vector<uint32_t> dsim_channels{' + ','.join('continuous_channel%d' % i for i in channels) + '};\n'
    for first in range(0, len(starts), batch):
        last = min(first + batch, len(starts))
        name = 'dsim_split_register_%d' % len(parts)
        declaration = 'void ' + name + '(dsim::Sim& s,const std::vector<uint32_t>& channels)'
        declarations += declaration + ';\n'
        body_end = starts[last] if last < len(starts) else ends[-1]
        parts.append(declaration + '{\n' + aliases + main[starts[first]:body_end] + '\n}\n')
        calls += name + '(s,dsim_channels);\n'
    return common + declarations, parts, main[:starts[0]] + calls + main[ends[-1]:], len(starts)


def split_setup(entry, batch):
    """Move contiguous, self-contained setup calls without changing their order.

    These generated calls use only Sim, numeric literals, and shared model
    definitions. Other statements and preprocessor branches stay in main.
    """
    pattern = re.compile(r'^s\.(?:signal|signal_two_state|fixed_array|connect_net|add_wait_site|add_expression_wait_site)\(', re.M)
    matches = list(pattern.finditer(entry))
    ranges = [(m.start(), registration_end(entry, m.start())) for m in matches]
    groups = []
    for start, end in ranges:
        if groups and entry[groups[-1][-1][1]:start].strip().startswith('//'):
            gap = entry[groups[-1][-1][1]:start]
            contiguous = len(gap.strip().splitlines()) == 1
        else:
            contiguous = bool(groups) and not entry[groups[-1][-1][1]:start].strip()
        if contiguous:
            groups[-1].append((start, end))
        else:
            groups.append([(start, end)])
    units, replacements, declarations = [], [], ''
    for group in groups:
        if len(group) < batch:
            continue
        for first in range(0, len(group), batch):
            chunk = group[first:first + batch]
            name = 'dsim_split_setup_%d' % len(units)
            declaration = 'void ' + name + '(dsim::Sim& s)'
            declarations += declaration + ';\n'
            units.append(declaration + '{\n' + entry[chunk[0][0]:chunk[-1][1]] + '\n}\n')
            replacements.append((chunk[0][0], chunk[-1][1], name + '(s);'))
    for start, end, call in reversed(replacements):
        entry = entry[:start] + call + entry[end:]
    # Large startup exclusion chains are both expensive to compile and O(N*M)
    # to execute. Scan the same excluded IDs in order instead.
    startup = re.compile(r'for\(int i=0;i<int\(s\.processes\.size\(\)\);\+\+i\)if\((i!=\d+(?:&&i!=\d+)*)\) ?s\.enqueue\(i\);')
    def replace_startup(match):
        ids = sorted(set(map(int, re.findall(r'i!=(\d+)', match.group(1)))))
        return ('{const std::vector<int> dormant{' + ','.join(map(str, ids)) + '};size_t next=0;'
                'for(int i=0;i<int(s.processes.size());++i){'
                'while(next<dormant.size()&&dormant[next]<i)++next;'
                'if(next==dormant.size()||dormant[next]!=i)s.enqueue(i);}}')
    entry = startup.sub(replace_startup, entry)
    return declarations + entry, units


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('source', type=Path)
    ap.add_argument('work', type=Path)
    ap.add_argument('--cxx', default='c++')
    ap.add_argument('--batch', type=int, default=4096)
    ap.add_argument('--jobs', type=int, default=4)
    ap.add_argument('--timeout', type=int, default=900)
    ap.add_argument('--cxx-flag', action='append', default=[])
    ap.add_argument('--emit-only', action='store_true')
    ap.add_argument('--split-setup', action='store_true', help='also split large signal, connection and wait registration blocks')
    ap.add_argument('--reuse', type=Path, help='reuse successfully compiled units only when generated source, common header and flags match')
    args = ap.parse_args()
    if min(args.batch, args.jobs, args.timeout) < 1:
        ap.error('batch, jobs and timeout must be positive')
    source = args.source.resolve().read_text()
    common, parts, entry, processes = split(source, args.batch)
    setup = []
    if args.split_setup:
        entry, setup = split_setup(entry, args.batch)
    work = args.work.resolve()
    work.mkdir(parents=True, exist_ok=True)
    manifest = {'source_sha256': hashlib.sha256(source.encode()).hexdigest(), 'batch': args.batch,
                'processes': processes, 'parts': len(parts), 'cxx': args.cxx, 'flags': args.cxx_flag,
                'split_setup': args.split_setup, 'setup_parts': len(setup),
                'splitter_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    old = work / 'inputs.json'
    if old.exists():
        if json.loads(old.read_text()) != manifest:
            raise ValueError('work directory contains a different model or build configuration')
    elif any(work.iterdir()):
        raise ValueError('work directory must be empty or owned by this exact build')
    old.write_text(json.dumps(manifest, indent=2) + '\n')
    (work / 'common.hpp').write_text('#pragma once\n' + common)
    units = []
    for i, body in enumerate(parts + [entry] + setup):
        unit = work / ('part-%04d.cpp' % i)
        unit.write_text('#include "common.hpp"\n' + body)
        units.append(unit)
    if args.emit_only:
        print(json.dumps(dict(status='SPLIT_ONLY_RUNTIME_UNTESTED', **manifest)))
        return 0
    flags = ['-std=c++17', '-O0']
    if Path(args.cxx).name in ['icpx', 'icpc']:
        flags.append('-fp-model=strict')
    flags += args.cxx_flag
    report = {'status': 'RUNNING', 'inputs': manifest, 'compiles': {}}
    reuse = args.reuse.resolve() if args.reuse else None
    if reuse:
        previous = json.loads((reuse / 'inputs.json').read_text())
        for key in ['source_sha256', 'batch', 'cxx', 'flags']:
            if previous[key] != manifest[key]:
                raise ValueError('reuse configuration differs: ' + key)
        if (reuse / 'common.hpp').read_bytes() != (work / 'common.hpp').read_bytes():
            raise ValueError('reuse common definitions differ')
        old_results = json.loads((reuse / 'results.json').read_text())['compiles']

    def run(label, command):
        (work / (label + '.command.json')).write_text(json.dumps(command) + '\n')
        start = time.monotonic()
        with (work / (label + '.stdout')).open('w') as out, (work / (label + '.stderr')).open('w') as err:
            p = subprocess.Popen(command, stdout=out, stderr=err, cwd=work, start_new_session=True)
            try:
                code = p.wait(timeout=args.timeout)
            except subprocess.TimeoutExpired:
                os.killpg(p.pid, signal.SIGKILL)
                p.wait()
                code = 'TIMEOUT'
        return {'returncode': code, 'seconds': time.monotonic() - start}

    def compile_unit(unit):
        obj = unit.with_suffix('.o')
        if obj.exists():
            return unit.name, {'returncode': 0, 'reused_object': True}
        if reuse and unit.name in old_results and old_results[unit.name]['returncode'] == 0:
            old_unit = reuse / unit.name
            old_obj = old_unit.with_suffix('.o')
            if old_obj.is_file() and old_unit.read_bytes() == unit.read_bytes():
                import shutil
                shutil.copyfile(old_obj, obj)
                return unit.name, {'returncode': 0, 'reused_from': str(old_obj),
                                   'object_sha256': hashlib.sha256(obj.read_bytes()).hexdigest()}
        temporary = obj.with_suffix('.o.tmp')
        result = run(unit.stem, [args.cxx, *flags, '-c', str(unit), '-o', str(temporary)])
        if result['returncode'] == 0:
            temporary.replace(obj)
        else:
            temporary.unlink(missing_ok=True)
        return unit.name, result

    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for future in as_completed([pool.submit(compile_unit, unit) for unit in units]):
            name, result = future.result()
            report['compiles'][name] = result
            (work / 'results.json').write_text(json.dumps(report, indent=2) + '\n')
            print(name, result['returncode'], flush=True)
    if all(result['returncode'] == 0 for result in report['compiles'].values()):
        command = [args.cxx, *flags, *map(str, [unit.with_suffix('.o') for unit in units]), '-o', str(work / 'native.tmp')]
        report['link'] = run('link', command)
        if report['link']['returncode'] == 0:
            (work / 'native.tmp').replace(work / 'native')
            report['status'] = 'COMPILE_PASS_RUNTIME_UNTESTED'
        else:
            report['status'] = 'LINK_FAILED'
    else:
        report['status'] = 'COMPILE_FAILED'
    (work / 'results.json').write_text(json.dumps(report, indent=2) + '\n')
    print(report['status'])
    return 0 if report['status'] == 'COMPILE_PASS_RUNTIME_UNTESTED' else 1


if __name__ == '__main__':
    raise SystemExit(main())
