void OutputC(module* mod, const char *ofname)
{
  char oputfname[1024];
  sprintf(oputfname, "%sEquation.cc", ofname);
  ofstream ofs(oputfname);
  string className = "Ahdl" + mod->_name + "DeviceEvaluator";

  ofs<<"#include \"AhdlResDeviceEvaluator.h\""<<endl;
  ofs<<"#include \"ahdl/ResModel.h\""<<endl<<endl;

  ofs<<"typedef ResModel::Net Net;\n";
  ofs<<"typedef ResModel::Elem Elem;\n\n";

  //// output ProvideSparseStructure
  ofs<<"void "<<
     className<<"::ProvideSparseStructure()\n";
  ofs<<"{\n";
  ofs<<"    int netnum["<<mod->_net.size()<<"];\n";
  for(int i=0; i<mod->_net.size(); ++i){
    ofs<<"    netnum["<<i<<"] = variableIndex_[Net::"
      <<mod->_net[i]._name<<"];"<<endl;
  }
  for(int i=0; i<mod->_net.size(); ++i){
    for(int j=0; j<mod->_net.size(); ++j){
      if(mod->_matstructrue[i][j] == 1)
        ofs<<"    equation_->AllocateMatrixElement(netnum["
          <<i<<"], netnum["<<j<<"]);\n";
    }
  }
  ofs<<"    for(int i = 0; i < "<<mod->_net.size()<<"; ++i) {\n";
  ofs<<"        equation_->AllocateRhs(variableIndex_[i]);\n";
  ofs<<"    }\n";
  ofs<<"}\n\n"; //end of ProvideSparseStructure

  /// output InitializeSubMatrixPointer
  ofs<<"void "<<
    className<<"::InitializeSubMatrixPointer()\n";
  ofs<<"{\n";
  ofs<<"    int netnum["<<mod->_net.size()<<"];\n";
  for(int i=0; i<mod->_net.size(); ++i){
    ofs<<"    netnum["<<i<<"] = variableIndex_[Net::"
      <<mod->_net[i]._name<<"];"<<endl;
  }
  for(int i=0; i<mod->_net.size(); ++i){
    for(int j=0; j<mod->_net.size(); ++j){
      if(mod->_matstructrue[i][j] == 1)
        ofs<<"    matPosition_["<<i<<"]["<<j<<"] = "
          <<"equation->GetMatrixElementPosition"
          <<"(netnum["<<i<<"], netnum["<<j<<"]);\n";
    }
  }
  ofs<<endl;
  ofs<<"    for(int i = 0; i < "<<mod->_net.size()<<"; ++i) {\n";
  ofs<<"        rhsPosition_[i] = equation_->GetRhsPosition(variableIndex_[i]);\n";
  ofs<<"    }\n";
  ofs<<"}\n\n";  /// end of InitializeSubMatrixPointer

  /// output TimeDomainEquation
  ofs<<"void "<<
    className<<"::ProvideTimeDomainEquation()\n";
  ofs<<"{\n";
  ofs<<EquationGenerator(mod);
  ofs<<"}\n\n";/// end of Equation

  /// output TimeDomainJacobi
  ofs<<"void "<<
    className<<"::ProvideTimeDomainJacobi()\n";
  ofs<<"{\n";
  ofs<<JacobiGenerator(mod);
  ofs<<"}\n\n";/// end of Jacobi

  ofs.close();
  ofs.clear();
}

string EquationGenerator(module *mod)
{
  string equStr;
  string ddtexp, ddtans;
  string stri;

  /// Begin Variable define
  for(int i=0; i<mod->_ddtnum; ++i){
    ddtexp += ", DdtExp" + int2string(i);
    ddtans += ", DdtAns" + int2string(i);
  }
  equStr += "    double" + ddtexp.substr(1) + ";\n";
  equStr += "    double" + ddtans.substr(1) + ";\n";
  equStr += "    int netnum[" + int2string(mod->_net.size()) + "];\n";
  for(int i=0; i<mod->_net.size(); ++i){
    stri = int2string(i);
    equStr += "    netnum["+ stri +
      "] = variableIndex_[Net::" + mod->_net[i]._name + "];\n";
  }
  for(int i=0; i<mod->_net.size(); ++i){
    stri = int2string(i);
    equStr += "    double _rhsN" + stri + " = 0;\n";
  }
  map<string, int>::iterator dervit = mod->_dervar.begin();
  while(dervit != mod->_dervar.end()){
    equStr += "    double "
      + dervit->first.substr(1, (dervit->first).find("Dv")-1)
      + " = equation->GetAnalogValue(netnum["
      + int2string(dervit->second) + "]);\n";
    ++dervit;
  } // End of variable define

  /// begin calculate
  string destmp;
  int flownode;
  source *mysource;
  list<statement>::iterator iter = mod->_main._steps.begin();
  list<source*>::iterator sourceiter;
  sourceiter = mod->_contribute.begin();
  while(iter != mod->_main._steps.end()){
    if(iter->_mode == 4 || iter->_mode == 5) {
      ++iter; continue;
    } else if(iter->_mode == 2){
      destmp = ReplaceModelParam(*iter);
      mysource = *sourceiter;
      ++sourceiter;
      if(mysource->_type == 1){
        if(mysource->_nodenum == 1){
          equStr += "    _rhsN" + int2string(mysource->_pos) + " += -(" + destmp + ");\n";
        } else if(mysource->_nodenum == 2){
          equStr += "    _rhsN" + int2string(mysource->_pos) + " += -(" + destmp + ");\n";
          equStr += "    _rhsN" + int2string(mysource->_neg) + " += (" + destmp + ");\n";
        } else {
          cerr<<"Too many nodes in source."<<endl;
          exit(-1);
        }
      } else if (mysource->_type == 2){
        if(mysource->_nodenum == 1){
          cerr<<"V(node) not impl yet.\n";
          exit(-1);
        } else if (mysource->_nodenum == 2){
          flownode = GetFlowNode(mysource->_pos, mysource->_neg);
          equStr += "    _rhsN" + int2string(flownode) + " += " + destmp +";\n";
        } else {
          cerr<<"Too many nodes in source."<<endl;
          exit(-1);
        }
      }
    } else {
      equStr += "    " + ReplaceModelParam(*iter) + "\n";
    }
    ++iter;
  }
  /// stamp RHS
  for(int i=0; i<mod->_net.size(); ++i){
    equStr += "    equation->AddtoCachedRhs(netnum[" + int2string(i)
      + "], rhsPosition_[Net::" + mod->_net[i]._name
      + "], _rhsN" + int2string(i) + ", 1);\n";
  }
  return equStr;
}

string JacobiGenerator(module *mod)
{
  string jacStr;
  string ddtexp, ddtans;
  string stri;

  /// begin variables declaration
  jacStr += "    double _der0 = equation_->DdtConduct();\n";
    for(int i=0; i<mod->_ddtnum; ++i){
    ddtexp += ", DdtExp" + int2string(i);
    ddtans += ", DdtAns" + int2string(i);
  }
  jacStr += "    double" + ddtexp.substr(1) + ";\n";
  jacStr += "    double" + ddtans.substr(1) + ";\n";
  jacStr += "    int netnum[" + int2string(mod->_net.size()) + "];\n";

  map<string, int>::iterator dervit = mod->_dervar.begin();
  while(dervit != mod->_dervar.end()){
    jacStr += "    double "
      + dervit->first.substr(1, (dervit->first).find("Dv")-1)
      + " = equation->GetAnalogValue(netnum["
      + int2string(dervit->second) + "]);\n";
    jacStr += "    double " + dervit->first + " = 1;\n";
    ++dervit;
  }
  for(int i=0; i<mod->_net.size(); ++i){
    stri = int2string(i);
    jacStr += "    netnum["+ stri +
      "] = variableIndex_[Net::" + mod->_net[i]._name + "];\n";
  }

  map<string, int>::iterator tmpvariter = mod->_tmpdervar.begin();
  int count = 0;
  while(tmpvariter != mod->_tmpdervar.end()){
    if(count%5 == 0){
      if(count > 1) jacStr += ";\n";
      jacStr += "    double " + tmpvariter->first;
    }
    else jacStr += ", " + tmpvariter->first;
    ++tmpvariter;
    ++count;
  }
  if(count) jacStr += ";\n";
  jacStr += "    double contributetmp";
  for(int i=0; i<gModule->_net.size(); ++i){
    if(i%4 == 0) jacStr += ";\n    double dcontributetmpDv" + int2string(i);
    else jacStr += ", dcontributetmpDv" + int2string(i);
  }
  jacStr += ";\n\n";

  // begin current calculate and derivation calculate
  string mainstr;
  statement mystat;
  set<string> dertmpvar;
  bitset<BIT_> tmpbit;
  map<string, bitset<BIT_> >::iterator viter;
  string destmp;
  source *mysource;
  list<statement>::iterator iter = mod->_main._steps.begin();
  list<source*>::iterator sourceiter;
  sourceiter = mod->_contribute.begin();
  while(iter != mod->_main._steps.end()){
    if(iter->_mode == 4) {
      mainstr += "            " + iter->_describ + "\n";
    } else if(iter->_mode == 2){
      mysource = *sourceiter;
      ++sourceiter;
      tmpbit = 0;
      viter = iter->_var.begin();
      while(viter != iter->_var.end()){
        tmpbit |= viter->second;
        ++viter;
      }
      destmp = "            contributetmp = " + iter->_describ + ";\n";
      destmp += "//Derivate " + int2string(tmpbit.to_ulong());
      mystat = *iter;
      mystat._describ = "            contributetmp = " + iter->_describ + ";";
      if(tmpbit != 0){
        destmp = calculate_deriv(mystat, dertmpvar);
        destmp = ReplaceModelParam(destmp, mystat._param);
      } else {
        destmp = ReplaceModelParam(destmp, mystat._param);
      }
      // Derivate of contributetmp`
      mainstr += destmp + "\n";
      if(mysource->_type == 1){
        if(mysource->_nodenum == 2){
          for(int i=0; i<mod->_net.size(); ++i){
            if(tmpbit[i] != 0){
              mainstr += "            _matValueN" + int2string(mysource->_pos) + "N" + 
                int2string(i) + " += dcontributetmpDv" + int2string(i) + ";\n";
              mainstr += "            _matValueN" + int2string(mysource->_neg) + "N" + 
                int2string(i) + " += -dcontributetmpDv" + int2string(i) + ";\n";
            }
          }
        } else if(mysource->_nodenum == 1){
          for(int i=0; i<mod->_net.size(); ++i){
            if(tmpbit[i] != 0){
              mainstr += "            _matValueN" + int2string(mysource->_pos) + "N"
                + int2string(i) + " += dcontributetmpDv" + int2string(i) + ";\n";
            }
          }
        }
      } else if (mysource->_type == 2){
        if(mysource->_nodenum == 1){
          cerr<<"V(node) not impl yet.\n";
          exit(-1);
        } else if (mysource->_nodenum == 2){

        } else {
          cerr<<"Too many nodes in source."<<endl;
          exit(-1);
        }
      }
    } else if(iter->_mode == 0){
      if(iter->_type == true)
      {
        destmp = calculate_deriv(*iter, dertmpvar);
        destmp = ReplaceModelParam(destmp, iter->_param);
        mainstr += destmp + "\n";
      } else {
        mainstr += ReplaceModelParam(*iter) + "\n";
      }
    }
    ++iter;
  }

  /// stamp matrix
  for(int i=0; i<mod->_net.size(); ++i){
    for(int j=0; j<mod->_net.size(); ++j){
      if(mod->_matstructrue[i][j] == 1){
        jacStr += "    double _matValueN" + int2string(i) + "N" + int2string(j) + " = 0;\n";
      }
    }
  }
  jacStr += mainstr;
  for(int i=0; i<mod->_net.size(); ++i){
    for(int j=0; j<mod->_net.size(); ++j){
      if(mod->_matstructrue[i][j] == 1){
        jacStr += "    equation->SetCachedMatrix(matEleN" + int2string(i) + "N" +
          int2string(j) + " , _matValueN" + int2string(i) + "N" + int2string(j) + ");\n";
      }
    }
  }

  return jacStr;
}
