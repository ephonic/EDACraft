void OutputSyntax(module* mod)
{
  char oputfname[1024];
  map<string, bitset<BIT_> >::iterator it;
  map<string, int>::iterator pit;
  list<statement>::iterator iter = mod->_main._steps.end();
  while(iter != mod->_main._steps.end()){
    cout<<iter->_describ<<endl;
    cout<<"    //";
    it = iter->_var.begin();
    while(it != iter->_var.end()){
      cout<<it->first<<"  "<<it->second<<"\t";
      ++it;
    }
    pit = iter->_param.begin();
    while(pit != iter->_param.end()){
      cout<<pit->first<<"\t";
      ++pit;
    }
    cout<<endl;
    ++iter;
  }

  ofstream ofs("model.syntax");

  /// parameter output.
  list<parameter>::iterator paramit;
  paramit = mod->_param.begin();
  string eleparam;
  string modparam;
  string port;
  string net;
  string ddtval, ddtexp, ddtans;
  while(paramit != mod->_param.end()){
    if(paramit->_type == 1) eleparam += " " + paramit->_name + "=" + double2string(paramit->_defvalue);
    else modparam += " " + paramit->_name + "=" + double2string(paramit->_defvalue);
    ++paramit;
  }
  /// port output
  for(int i=0; i<mod->_port.size(); ++i){
    port += " " + mod->_port[i]._name;
  }
  /// net output
  for(int i=0; i<mod->_net.size(); ++i){
    net += " " + mod->_net[i]._name;
  }
  for(int i=0; i<mod->_ddtnum; ++i){
    ddtval += " DdtVal" + int2string(i);
  }
  ofs<<mod->_name<<endl<<"begin\n";
  transform(eleparam.begin(), eleparam.end(), eleparam.begin(), ::tolower);
  transform(modparam.begin(), modparam.end(), modparam.begin(), ::tolower);
  ofs<<"@element@"<<eleparam<<";\n";
  ofs<<"@port@"<<port<<";\n";
  ofs<<"@net@"<<net<<";\n";
  ofs<<"@model@"<<modparam<<";\n";
  ofs<<"@state@"<<ddtval<<";\n";
  ofs<<"end\n";
  ofs.close();
  ofs.clear();
}


