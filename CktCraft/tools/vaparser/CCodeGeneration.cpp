void ModelCardGeneratorH(module* mod, const string &filename)
{
  char fn[1000];
  sprintf(fn, "%s.h", filename.c_str());
  ofstream ofs(fn);
  if(!ofs){
    cerr<<"File: "<<filename<<" cannot open for read.\n";
    exit(-1);
  }
  string className = mod->_name + "Model";
  int count;

  ofs<<"#ifndef verilog_ams_src_"<<filename<<"_H_\n";
  ofs<<"#define verilog_ams_src_"<<filename<<"_H_\n";
  ofs<<"/////////////////////////////////////////////////////////////////////////////////////////////////////\n";
  ofs<<"/// Generated by VA-C-Generator. DO NOT EDIT!\n";
  ofs<<"/// @author vaParser\n";
  ofs<<"/////////////////////////////////////////////////////////////////////////////////////////////////////\n\n";
  ofs<<"#include \"ahdl/AhdlModel.h\"\n"<<endl;

  ofs<<"class "<<className<<" : public AhdlModel\n";
  ofs<<"{\npublic:\n";

  /// output Net
  ofs<<"    struct Net\n    {\n";
  ofs<<"        enum Name\n        {\n";
  ofs<<"            ";
  vector<net>::iterator netiter = mod->_net.begin();
  count = 0;
  while(netiter != mod->_net.end()){
    if(count != 0)ofs<<", ";
    ofs<<netiter->_name<<" = "<<count;
    ++count;
    ++netiter;
  }
  ofs<<endl;
  ofs<<"        };\n    };\n\n"; ///Endof output Net;

  /// output parameter
  ofs<<"    struct Elem\n    {\n";
  ofs<<"        enum Name\n        {\n";
  ofs<<"            ";
  list<parameter>::iterator pariter = mod->_param.begin();
  count = 0;
  while(pariter != mod->_param.end()){
    if(count != 0) ofs<<", ";
    ofs<<pariter->_name<<" = "<<count;
    ++count;
    ++pariter;
  }
  ofs<<endl;
  ofs<<"        };\n    };\n"; ///End of output parameter

  ofs<<"\n\n";
  ofs<<"    "<<className<<"();\n";
  ofs<<"\n";
  ofs<<"};\n\n";
  ofs<<"#endif\n";

  ofs.close();
  ofs.clear();
}


